-- SELECT ... WHERE 
-- Задача: вывести государства, у которых вид управления "Республика"
-- где столица не Москва.
SELECT
    "Название",
    "Столица",
    "Вид_управления"
FROM "Государство"
WHERE "Вид_управления" = 'Республика'
  AND "Столица" <> 'Москва';

-- JOIN
-- Задача: вывести национальность и страну, в которой она указана.
-- связываем "Национальность" с "Государство" по внешнему ключу.
SELECT
    Н."Название" AS "Национальность",
    Г."Название" AS "Государство"
FROM "Национальность" Н
JOIN "Государство" Г
  ON Н."Государство_Название_фк" = Г."Название";