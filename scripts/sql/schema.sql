DROP TABLE IF EXISTS "Национальность";
DROP TABLE IF EXISTS "Население";
DROP TABLE IF EXISTS "Государство";

CREATE TABLE "Государство" (
    "Название"       VARCHAR(100) PRIMARY KEY,
    "Столица"        VARCHAR(100) NOT NULL,
    "Вид_управления" VARCHAR(50)  NOT NULL
);

CREATE TABLE "Население" (
    "Население_ID"        SERIAL PRIMARY KEY,
    "Численность"         INT NOT NULL CHECK ("Численность" >= 0),
    "Мужская_численность" INT NOT NULL CHECK ("Мужская_численность" >= 0),
    "Женская_численность" INT NOT NULL CHECK ("Женская_численность" >= 0)
);

CREATE TABLE "Национальность" (
    "Национальность_ID"          SERIAL PRIMARY KEY,
    "Язык"                       VARCHAR(50) NOT NULL,
    "Общая_численость"           INT NOT NULL CHECK ("Общая_численость" >= 0),
    "Название"                   VARCHAR(50) NOT NULL,
    "Государство_Название_фк"    VARCHAR(100) NOT NULL
        REFERENCES "Государство"("Название") ON DELETE RESTRICT,
    "Население_ID_FK"            INT NOT NULL
        REFERENCES "Население"("Население_ID") ON DELETE RESTRICT
);

